BEGIN;

CREATE TABLE game_rule_versions (
    rule_version VARCHAR(32) PRIMARY KEY,
    description VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_game_rule_versions_active
    ON game_rule_versions (active)
    WHERE active;

CREATE TABLE game_sessions (
    session_id VARCHAR(80) PRIMARY KEY,
    state_version SMALLINT NOT NULL CHECK (state_version > 0),
    rule_version VARCHAR(32) NOT NULL REFERENCES game_rule_versions(rule_version),
    language VARCHAR(2) NOT NULL CHECK (language IN ('zh', 'en')),
    phase VARCHAR(16) NOT NULL CHECK (phase IN ('welcome', 'pretest', 'briefing', 'game', 'result')),
    current_round SMALLINT NOT NULL CHECK (current_round > 0),
    max_rounds SMALLINT NOT NULL CHECK (max_rounds > 0),
    failures SMALLINT NOT NULL DEFAULT 0 CHECK (failures >= 0),
    state_payload JSONB NOT NULL CHECK (jsonb_typeof(state_payload) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE round_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(80) NOT NULL REFERENCES game_sessions(session_id) ON DELETE CASCADE,
    round_number SMALLINT NOT NULL CHECK (round_number > 0),
    rule_version VARCHAR(32) NOT NULL REFERENCES game_rule_versions(rule_version),
    event_id VARCHAR(80) NOT NULL,
    action_id VARCHAR(80) NOT NULL,
    district VARCHAR(40) NOT NULL,
    before_metrics JSONB NOT NULL CHECK (jsonb_typeof(before_metrics) = 'object'),
    after_metrics JSONB NOT NULL CHECK (jsonb_typeof(after_metrics) = 'object'),
    supply_breakdown JSONB NOT NULL CHECK (jsonb_typeof(supply_breakdown) = 'object'),
    risk_breakdown JSONB NOT NULL CHECK (jsonb_typeof(risk_breakdown) = 'object'),
    round_payload JSONB NOT NULL CHECK (jsonb_typeof(round_payload) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_round_records_session_round UNIQUE (session_id, round_number)
);

CREATE TABLE anonymous_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(80) NOT NULL REFERENCES game_sessions(session_id) ON DELETE CASCADE,
    event_name VARCHAR(40) NOT NULL CHECK (
        event_name IN ('session_started', 'quiz_completed', 'decision_confirmed', 'game_completed')
    ),
    round_number SMALLINT CHECK (round_number IS NULL OR round_number > 0),
    crisis_event_id VARCHAR(80),
    action_id VARCHAR(80),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_game_sessions_updated_at ON game_sessions(updated_at DESC);
CREATE INDEX idx_round_records_session ON round_records(session_id, round_number);
CREATE INDEX idx_round_records_event ON round_records(event_id);
CREATE INDEX idx_round_records_district ON round_records(district);
CREATE INDEX idx_anonymous_events_session ON anonymous_events(session_id, created_at);
CREATE INDEX idx_anonymous_events_name ON anonymous_events(event_name, created_at);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_game_sessions_updated_at
    BEFORE UPDATE ON game_sessions
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

COMMIT;
